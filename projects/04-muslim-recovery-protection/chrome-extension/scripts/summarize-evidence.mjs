// Writes test-evidence/SUMMARY.md from the JSON files produced by the real-browser suites.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), 'test-evidence');
const files = fs.readdirSync(dir).filter(f => /^e2e-.*\.json$/u.test(f)).sort();
const lines = ['# Real-browser test evidence (generated)', '', 'Generated by `scripts/summarize-evidence.mjs` from the JSON files in this folder. PASS means the check ran in that real browser and passed; NOT_RUN means it could not run (reason given).', ''];
for (const file of files) {
    const { meta, summary, results, notes } = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    lines.push(`## ${meta.browser} ${meta.version}`, '', `- OS: ${meta.os} · Node ${meta.node} · run ${meta.date}`, ...(meta.addonInstall ? [`- Add-on install: ${meta.addonInstall}`] : []), ...(meta.note ? [`- Note: ${meta.note}`] : []),
        `- Result: ${Object.entries(summary).map(([k, v]) => `${k} ${v}`).join(' · ')}`, '', '| Check | Result | Detail |', '|---|---|---|');
    for (const r of results) lines.push(`| ${r.id.replaceAll('|', '/')} | ${r.status} | ${String(r.detail ?? '').replaceAll('|', '/').replaceAll('\n', ' ').slice(0, 140)} |`);
    if (notes.length) lines.push('', '**Measurements / notes**', '', ...notes.map(n => `- \`${n.id}\`: ${n.text}`));
    lines.push('');
}
fs.writeFileSync(path.join(dir, 'SUMMARY.md'), `${lines.join('\n')}\n`);
process.stdout.write(`wrote ${path.join(dir, 'SUMMARY.md')} (${files.length} browsers)\n`);
